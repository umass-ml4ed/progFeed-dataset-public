def divide_apples(apples, baskets):
    print(str(apples) + ' apples for')
    print(str(baskets) + ' baskets can be divided as')
    print(str(int(apples)//int(baskets)) + ' apples per basket with')
    print(str(int(apples)%int(baskets)) + ' leftover apples')

divide_apples(20, 3)